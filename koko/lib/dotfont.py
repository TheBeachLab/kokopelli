for _data in (_ASCII, _KATAKANA, _HIRAGANA, _SPECIAL):
    GLYPHS_5X7.update(_decode_glyphs(_data))


def _bits_to_row(bits: int) -> str:
    return f"{bits & 0x1F:05b}"


def _row_to_bits(row: str) -> int:
    return int(row, 2)


def _make_small(glyph: Glyph) -> Glyph:
    body = tuple(_bits_to_row(_row_to_bits(row) >> 1) for row in glyph[2:6])
    return ("00000", "00000", *body, "00000")  # type: ignore[return-value]


for _small, _full in zip("ぁぃぅぇぉ", "あいうえお"):
    GLYPHS_5X7[_small] = _make_small(GLYPHS_5X7[_full])


