def _box_glyph(directions: str, double: bool) -> Glyph:
    rows = [0] * GLYPH_HEIGHT
    horizontal_rows = (2, 4) if double else (3,)
    vertical_columns = (1, 3) if double else (2,)
    for row in horizontal_rows:
        if "L" in directions:
            for column in range(0, 3):
                rows[row] |= 1 << (4 - column)
        if "R" in directions:
            for column in range(2, 5):
                rows[row] |= 1 << (4 - column)
    for column in vertical_columns:
        if "U" in directions:
            for row in range(0, 4):
                rows[row] |= 1 << (4 - column)
        if "D" in directions:
            for row in range(3, 7):
                rows[row] |= 1 << (4 - column)
    return tuple(_bits_to_row(row) for row in rows)  # type: ignore[return-value]


for _character, _directions in _LIGHT_BOX_DIRECTIONS.items():
    GLYPHS_5X7[_character] = _box_glyph(_directions, double=False)
for _character, _directions in _DOUBLE_BOX_DIRECTIONS.items():
    GLYPHS_5X7[_character] = _box_glyph(_directions, double=True)

