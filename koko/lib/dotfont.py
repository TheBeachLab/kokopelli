def glyph(character: str) -> Glyph | None:
    """Return a glyph for one Unicode character, if the map can represent it."""

    if len(character) != 1:
        raise ValueError("glyph() expects exactly one Unicode character")
    if character in GLYPHS_5X7:
        return GLYPHS_5X7[character]
    if character in _ALIASES:
        return GLYPHS_5X7[_ALIASES[character]]
    generated = _accented_latin(character)
    if generated is not None:
        GLYPHS_5X7[character] = generated
    return generated


# Populate the public map eagerly so callers can inspect the full historical
# IBM-850 repertoire without invoking ``glyph`` first.
for _character in IBM_CP850_CHARACTERS:
    if glyph(_character) is None:
        raise RuntimeError(f"Missing IBM-850 5x7 glyph for U+{ord(_character):04X}")


_FULLWIDTH_TO_HALFWIDTH: dict[str, str] = {}
for _halfwidth in JIS_X0201_KATAKANA:
    _fullwidth = unicodedata.normalize("NFKC", _halfwidth)
    if len(_fullwidth) == 1:
        _FULLWIDTH_TO_HALFWIDTH[_fullwidth] = _halfwidth
for _base in JIS_X0201_KATAKANA:
    for _mark in ("ﾞ", "ﾟ"):
        _fullwidth = unicodedata.normalize("NFKC", _base + _mark)
        if len(_fullwidth) == 1:
            _FULLWIDTH_TO_HALFWIDTH[_fullwidth] = _base + _mark


def expand_character(character: str) -> str:
    """Expand one Unicode character into one or more available 5x7 cells."""

    if len(character) != 1:
        raise ValueError("expand_character() expects exactly one Unicode character")
    if glyph(character) is not None:
        return character
    if character in _FULLWIDTH_TO_HALFWIDTH:
        return _FULLWIDTH_TO_HALFWIDTH[character]

    decomposed = unicodedata.normalize("NFD", character)
    if decomposed and glyph(decomposed[0]) is not None:
        suffix = ""
        for mark in decomposed[1:]:
            if mark == "\N{COMBINING KATAKANA-HIRAGANA VOICED SOUND MARK}":
                suffix += "ﾞ"
            elif mark == "\N{COMBINING KATAKANA-HIRAGANA SEMI-VOICED SOUND MARK}":
                suffix += "ﾟ"
            else:
                return character
        return decomposed[0] + suffix
    return character


