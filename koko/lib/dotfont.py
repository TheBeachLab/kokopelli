def _remove_repeated_row(rows: list[str]) -> list[str]:
    for index in range(1, len(rows)):
        if rows[index] == rows[index - 1]:
            return rows[:index] + rows[index + 1 :]
    return rows[:3] + rows[4:]


def _accented_latin(character: str) -> Glyph | None:
    decomposed = unicodedata.normalize("NFD", character)
    if not decomposed or decomposed[0] not in GLYPHS_5X7:
        return None
    base = decomposed[0]
    if ord(base) >= 128 or not base.isalpha():
        return None
    top = next((_TOP_MARKS[mark] for mark in decomposed[1:] if mark in _TOP_MARKS), None)
    bottom = next(
        (_BOTTOM_MARKS[mark] for mark in decomposed[1:] if mark in _BOTTOM_MARKS), None
    )
    if top is None and bottom is None:
        return None

    rows = list(GLYPHS_5X7[base])
    if top is not None:
        if base.isupper():
            rows = [top] + _remove_repeated_row(rows)
        else:
            rows[0] = top
    if bottom is not None:
        if top is None:
            rows = rows[:6] + [bottom]
        else:
            rows[-1] = bottom
    return tuple(rows)  # type: ignore[return-value]


