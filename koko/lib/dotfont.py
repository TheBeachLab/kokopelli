"""Readable 5x7 bitmap glyph data for Kokopelli's fabrication font.

The public ``GLYPHS_5X7`` map stores each glyph as seven strings of five
binary digits, from top to bottom.  Keeping the source in this form makes the
font easy to inspect and edit without a font editor.

Character-set references:

* IBM documents code page 850 as its 8-bit ASCII Latin-1 multinational page:
  https://www.ibm.com/docs/en/i/7.5.0?topic=encodings-fileencoding-values-i-ccsid
* IBM identifies CCSID 897 as JIS X 0201.  Its Japanese portion is the
  half-width katakana repertoire used here.
* The ASCII and katakana forms follow the public-domain HD44780A00 5x7 table:
  https://commons.wikimedia.org/wiki/File:Charset.gif

The compact hiragana forms are adapted from Ethan Durrant's MIT-licensed
Vintage_Beauty character ROM.  The required license notice is preserved in
``THIRD_PARTY_NOTICES.md``.
"""

from __future__ import annotations

import unicodedata


GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
Glyph = tuple[str, str, str, str, str, str, str]


def _decode_glyphs(data: str) -> dict[str, Glyph]:
    glyphs: dict[str, Glyph] = {}
    for source_line in data.splitlines():
        line = source_line.partition("#")[0].strip()
        if not line:
            continue
        codepoint, encoded = line.split()
        rows = tuple(encoded.split("/"))
        if len(rows) != GLYPH_HEIGHT or any(
            len(row) != GLYPH_WIDTH or set(row) - {"0", "1"} for row in rows
        ):
            raise ValueError(f"Invalid 5x7 glyph record: {source_line}")
        glyphs[chr(int(codepoint, 16))] = rows  # type: ignore[assignment]
    return glyphs


